/** fetch JSON com tratamento de erro (sempre com barra final nas rotas, por causa do trailingSlash). */
export async function api(url, { method = 'GET', data, form } = {}) {
  const res = await fetch(url, {
    method,
    headers: data ? { 'Content-Type': 'application/json' } : undefined,
    body: form || (data ? JSON.stringify(data) : undefined),
    credentials: 'same-origin',
  });
  const out = await res.json().catch(() => ({}));
  if (res.status === 401 && !url.includes('/auth/')) { window.location.href = '/admin/login/'; throw new Error('Sessão expirada.'); }
  if (!res.ok) throw new Error(out.error || 'Algo deu errado. Tente novamente.');
  return out;
}

/** Toast simples sem provider: cria o elemento direto no DOM. */
export function toast(message, type = 'ok') {
  if (typeof document === 'undefined') return;
  let box = document.querySelector('.a-toasts');
  if (!box) { box = document.createElement('div'); box.className = 'a-toasts'; box.setAttribute('role', 'status'); box.setAttribute('aria-live', 'polite'); document.body.appendChild(box); }
  const el = document.createElement('div');
  el.className = `a-toast ${type}`; el.textContent = message; box.appendChild(el);
  setTimeout(() => { el.style.transition = 'opacity .3s, transform .3s'; el.style.opacity = '0'; el.style.transform = 'translateX(20px)'; setTimeout(() => el.remove(), 320); }, type === 'err' ? 6000 : 3500);
}

/** Executa uma ação assíncrona controlando o estado "ocupado" e mostrando erros em toast. */
export function useBusy() {
  const [busy, setBusy] = useState('');
  const run = async (key, fn) => {
    setBusy(key || 'x');
    try { return await fn(); } catch (e) { toast(e.message, 'err'); return undefined; } finally { setBusy(''); }
  };
  return [busy, run];
}

