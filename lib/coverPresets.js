export function getPresetById(id) {
  return COVER_PRESETS.find((p) => p.id === id) || COVER_PRESETS[0];
}

export function getRandomPresetUrl(presetId, seed = 0) {
  const preset = getPresetById(presetId);
  if (!preset.alts || !preset.alts.length) return preset.url;
  const idx = Math.abs(seed) % preset.alts.length;
  return preset.alts[idx] || preset.url;
}
